export const getTranslation = (lang = 'en', key = '') => {
  if (!key || typeof key !== 'string') return key;

  const targetLang = (lang || 'en').toLowerCase();

  // 1. Direct match in requested language dictionary
  const dict = translations[targetLang];
  if (dict && dict[key]) return dict[key];

  // 2. Direct match in phrase dictionary
  const phrases = phraseTranslations[targetLang];
  if (phrases && phrases[key]) return phrases[key];

  // 3. Cleaned key matching
  const cleanKey = key.replace(/^nav_/, '').replace(/_label$/, '').trim();
  if (dict) {
    if (dict[cleanKey]) return dict[cleanKey];
    const capKey = cleanKey.charAt(0).toUpperCase() + cleanKey.slice(1);
    if (dict[capKey]) return dict[capKey];
    const upperKey = cleanKey.toUpperCase();
    if (dict[upperKey]) return dict[upperKey];
  }
  if (phrases) {
    if (phrases[cleanKey]) return phrases[cleanKey];
    const capKey = cleanKey.charAt(0).toUpperCase() + cleanKey.slice(1);
    if (phrases[capKey]) return phrases[capKey];
  }

  // 4. Fallback to English dictionary
  if (targetLang !== 'en') {
    if (translations['en'] && translations['en'][key]) return translations['en'][key];
    if (phraseTranslations['en'] && phraseTranslations['en'][key]) return phraseTranslations['en'][key];
  }

  // 5. If key is natural text (contains spaces or full sentence), return key as-is
  if (key.includes(' ') || (key.length > 15 && !key.includes('_'))) return key;

  // 6. Format internal developer keys
  let formatted = cleanKey.replace(/_/g, ' ');
  return formatted.charAt(0).toUpperCase() + formatted.slice(1);
};
